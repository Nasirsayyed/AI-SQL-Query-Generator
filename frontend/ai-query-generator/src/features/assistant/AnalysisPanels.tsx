import { Alert, Box, Chip, List, ListItem, ListItemText, Stack, Table, TableBody, TableCell, TableHead, TableRow, Typography } from '@mui/material';
import type { ExecutionPlanSummary, ExplainSqlResponse, OptimizeSqlResponse } from '../../api/types';
import { formatNumber } from '../../utils/format';

export function ExplanationPanel({ explanation }: { explanation: ExplainSqlResponse }) {
  return (
    <Box>
      <Typography sx={{ mb: 2 }}>{explanation.summary}</Typography>
      <List dense disablePadding>
        {explanation.steps.map((s, i) => (
          <ListItem key={i} alignItems="flex-start" disableGutters>
            <Chip label={`${i + 1}. ${s.clause}`} size="small" color="primary" variant="outlined" sx={{ mr: 1.5, mt: 0.25, minWidth: 110 }} />
            <ListItemText primary={s.description} />
          </ListItem>
        ))}
      </List>
      {explanation.beginnerExplanation && (
        <Alert severity="info" sx={{ mt: 2 }} icon={false}>
          <Typography variant="subtitle2">In plain language</Typography>
          {explanation.beginnerExplanation}
        </Alert>
      )}
      {explanation.notes.length > 0 && (
        <Alert severity="warning" sx={{ mt: 2 }}>
          {explanation.notes.map((n, i) => <div key={i}>{n}</div>)}
        </Alert>
      )}
      <Typography variant="caption" color="text.secondary" sx={{ display: 'block', mt: 2 }}>
        Generated by {explanation.model} ({explanation.promptVersion}). The query was not executed.
      </Typography>
    </Box>
  );
}

export function OptimizationPanel({ optimization, onUse }: { optimization: OptimizeSqlResponse; onUse?: (sql: string) => void }) {
  const colors = { info: 'info', warning: 'warning', critical: 'error' } as const;
  return (
    <Box>
      <Typography sx={{ mb: 2 }}>{optimization.summary}</Typography>
      <Stack spacing={1}>
        {optimization.suggestions.map((s, i) => (
          <Alert key={i} severity={colors[s.severity]}>
            <strong>{s.title}</strong> — {s.description}
          </Alert>
        ))}
      </Stack>
      {optimization.optimizedSql && (
        <Box sx={{ mt: 2 }}>
          <Typography variant="subtitle2">Suggested query {optimization.optimizedSqlValidation?.isValid ? '(passes validation)' : '(fails validation — review carefully)'}</Typography>
          <Box component="pre" sx={{ p: 1.5, bgcolor: 'action.hover', borderRadius: 1, overflow: 'auto', fontSize: 13 }}>{optimization.optimizedSql}</Box>
          {onUse && (
            <Chip clickable color="primary" label="Use this SQL in the editor" onClick={() => onUse(optimization.optimizedSql!)} />
          )}
        </Box>
      )}
    </Box>
  );
}

export function PlanPanel({ plan }: { plan: ExecutionPlanSummary }) {
  return (
    <Box>
      <Stack direction="row" spacing={1} sx={{ mb: 2 }}>
        <Chip label={`Estimated cost ${plan.estimatedTotalCost}`} />
        <Chip label={`Estimated rows ${formatNumber(plan.estimatedRows)}`} />
      </Stack>
      {plan.missingIndexes.length > 0 && (
        <Alert severity="warning" sx={{ mb: 2 }}>
          SQL Server suggests missing indexes: {plan.missingIndexes.join('; ')}
        </Alert>
      )}
      {plan.warnings.length > 0 && <Alert severity="warning" sx={{ mb: 2 }}>Plan warnings: {plan.warnings.join(', ')}</Alert>}
      <Box sx={{ overflowX: 'auto' }}>
        <Table size="small">
          <TableHead>
            <TableRow>
              <TableCell>Operator</TableCell>
              <TableCell>Object</TableCell>
              <TableCell align="right">Est. rows</TableCell>
              <TableCell align="right">Subtree cost</TableCell>
            </TableRow>
          </TableHead>
          <TableBody>
            {plan.topOperators.map((o, i) => (
              <TableRow key={i}>
                <TableCell>{o.physicalOp}{o.logicalOp !== o.physicalOp ? ` (${o.logicalOp})` : ''}</TableCell>
                <TableCell>{o.objectName ?? '—'}</TableCell>
                <TableCell align="right">{formatNumber(o.estimatedRows, 1)}</TableCell>
                <TableCell align="right">{o.estimatedSubtreeCost}</TableCell>
              </TableRow>
            ))}
          </TableBody>
        </Table>
      </Box>
    </Box>
  );
}
